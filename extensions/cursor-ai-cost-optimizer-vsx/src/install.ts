/**
 * `cco-init --workspace <ws> --uninstall` (removes hook entries, generated agents, .cursor/cco.json and
 * .cursor/cco/ — foreign hook entries are preserved) plus the rule/skills/commands the extension added.
 * Falls back to an in-process removal when no runtime is available.
 */
export async function uninstallWorkspace(workspace: string, opts: Options): Promise<UninstallResult> {
  const p = workspacePaths(workspace);
  const manifest = readJsonOr<Manifest | null>(p.manifestPath, null);
  const removed: string[] = [];
  const hooksFileFound = fs.existsSync(p.hooksPath);
  const binaryForRun = fs.existsSync(p.binaryPath) ? p.binaryPath : opts.binaryPath;
  const init = await runPluginScriptAsync(workspace, "cco-init.mjs", ["--workspace", workspace, "--uninstall"], { ...opts, binaryPath: binaryForRun });
  if (!init.ran || init.status !== 0) {
    // in-process fallback: same effect as cco-init --uninstall
    const existing = readJsonOr<HooksFile | null>(p.hooksPath, null);
    if (existing) {
      const stripped = stripCcoHooks(existing);
      if (stripped) {
        writeJson(p.hooksPath, stripped);
      } else {
        fs.rmSync(p.hooksPath, { force: true });
      }
    }
    for (const name of CCO_AGENT_NAMES) {
      const file = path.join(p.agentsDir, `${name}.md`);
      if ((readTextOr(file) || "").includes(GENERATED_AGENT_MARKER)) {
        fs.rmSync(file, { force: true });
        removed.push(toPosix(path.relative(workspace, file)));
      }
    }
    fs.rmSync(p.configPath, { force: true });
  }
  if (fs.existsSync(p.ccoDir)) {
    fs.rmSync(p.ccoDir, { recursive: true, force: true });
  }
  removed.push(".cursor/cco/", ".cursor/cco-hook.mjs", ".cursor/cco.json", ".cursor/agents/cco-*.md (generated)");
  const files = manifest?.files || extensionAssetList(opts.pluginRoot);
  for (const rel of files) {
    if (rel.startsWith(".cursor/cco/")) {
      continue;
    }
    const abs = path.join(workspace, ...rel.split("/"));
    if (fs.existsSync(abs)) {
      fs.rmSync(abs, { force: true });
      removed.push(rel);
    }
  }
  for (const d of [p.skillsDir]) {
    if (fs.existsSync(d)) {
      for (const entry of fs.readdirSync(d)) {
        rmdirIfEmpty(path.join(d, entry));
      }
    }
  }
  for (const d of [p.rulesDir, p.skillsDir, p.commandsDir, p.agentsDir]) {
    rmdirIfEmpty(d);
  }
  rmdirIfEmpty(p.cursorDir);
  return { removed, init, hooksFileFound };
}
