export function isCcoHookCommand(command: unknown): boolean {
  return typeof command === "string" && CCO_HOOK_COMMAND_RE.test(command);
}
export function quoteCommandPath(p: string): string {
  return `"${p.replace(/"/g, '\\"')}"`;
}
export function hookCommandFor(event: string, mode: HookMode, binaryPath?: string | null): string {
  return mode === "binary" && binaryPath ? `${quoteCommandPath(binaryPath)} ${event}` : `node .cursor/cco-hook.mjs ${event}`;
}
/** Account for the plugin's hooks/hooks.json entries (keeps matcher/timeout). */
export function buildHookEntries(pluginHooks: HooksFile, mode: HookMode, binaryPath?: string | null): Record<string, HookEntry[]> {
  const out: Record<string, HookEntry[]> = {};
  for (const [event, entries] of Object.entries(pluginHooks?.hooks || {})) {
    if (!Array.isArray(entries)) {
      continue;
    }
    out[event] = entries
      .filter((e) => e && typeof e.command === "string")
      .map((e) => {
        const entry: HookEntry = { ...e, command: hookCommandFor(event, mode, binaryPath) };
        if (entry.matcher === undefined) {
          delete entry.matcher;
        }
        if (entry.timeout === undefined) {
          delete entry.timeout;
        }
        return entry;
      });
  }
  return out;
}
/** Keep foreign entries, drop previous CCO entries (any event), append ours. */
export function mergeHooks(existing: HooksFile | null | undefined, ours: Record<string, HookEntry[]>): HooksFile {
  const base: HooksFile = existing && typeof existing === "object" ? { ...existing } : {};
  base.version = typeof base.version === "number" ? base.version : 1;
  const merged: Record<string, HookEntry[]> = {};
  for (const [event, entries] of Object.entries(base.hooks && typeof base.hooks === "object" ? base.hooks : {})) {
    const kept = (Array.isArray(entries) ? entries : []).filter((e) => !isCcoHookCommand(e?.command));
    if (kept.length) {
      merged[event] = kept;
    }
  }
  for (const [event, entries] of Object.entries(ours)) {
    if (entries.length) {
      merged[event] = [...(merged[event] || []), ...entries];
    }
  }
  base.hooks = merged;
  return base;
}
export function stripCcoHooks(existing: HooksFile | null | undefined): HooksFile | null {
  if (!existing || typeof existing !== "object") {
    return null;
  }
  const out = mergeHooks(existing, {});
  const otherKeys = Object.keys(out).filter((k) => k !== "version" && k !== "hooks");
  return Object.keys(out.hooks || {}).length === 0 && otherKeys.length === 0 ? null : out;
}
export function ccoHookEntries(file: HooksFile | null | undefined): Record<string, HookEntry[]> {
  const out: Record<string, HookEntry[]> = {};
  for (const [event, entries] of Object.entries(file?.hooks || {})) {
    const ours = (Array.isArray(entries) ? entries : []).filter((e) => isCcoHookCommand(e?.command));
    if (ours.length) {
      out[event] = ours;
    }
  }
  return out;
}
function sameEntries(a: Record<string, HookEntry[]>, b: Record<string, HookEntry[]>): boolean {
  const norm = (x: Record<string, HookEntry[]>) => JSON.stringify(Object.keys(x).sort().map((k) => [k, x[k].map((e) => JSON.stringify(e)).sort()]));
  return norm(a) === norm(b);
}
/** Rewrite our entries in <ws>/.cursor/hooks.json to the given form; returns the events written. */
function writeHookEntries(workspace: string, opts: Options, mode: HookMode, binaryPath: string | null): string[] {
  const p = workspacePaths(workspace);
  const pluginHooks = readJsonOr<HooksFile>(path.join(opts.pluginRoot, "hooks", "hooks.json"), { version: 1, hooks: {} });
  const ours = buildHookEntries(pluginHooks, mode, binaryPath);
  writeJson(p.hooksPath, mergeHooks(readJsonOr<HooksFile | null>(p.hooksPath, null), ours));
  return Object.keys(ours);
}

