function ensureDir(p: string): void {
  fs.mkdirSync(p, { recursive: true });
}
function readJsonOr<T>(filePath: string, fallback: T): T {
  try {
    return JSON.parse(fs.readFileSync(filePath, "utf8")) as T;
  } catch {
    return fallback;
  }
}
function writeJson(filePath: string, value: unknown): void {
  ensureDir(path.dirname(filePath));
  fs.writeFileSync(filePath, `${JSON.stringify(value, null, 2)}\n`, "utf8");
}
function readTextOr(filePath: string, fallback: string | null = null): string | null {
  try {
    return fs.readFileSync(filePath, "utf8");
  } catch {
    return fallback;
  }
}
export function listFiles(dir: string, prefix = ""): string[] {
  if (!fs.existsSync(dir)) {
    return [];
  }
  const out: string[] = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const rel = prefix ? `${prefix}/${entry.name}` : entry.name;
    if (entry.isDirectory()) {
      out.push(...listFiles(path.join(dir, entry.name), rel));
    } else if (entry.isFile()) {
      out.push(rel);
    }
  }
  return out.sort();
}
function sha256File(filePath: string): string {
  return crypto.createHash("sha256").update(fs.readFileSync(filePath)).digest("hex");
}
function sameFile(a: string, b: string): boolean {
  try {
    const sa = fs.statSync(a);
    const sb = fs.statSync(b);
    if (sa.size !== sb.size) {
      return false;
    }
  } catch {
    return false;
  }
  try {
    return fs.statSync(a).size === fs.statSync(b).size && sha256File(a) === sha256File(b);
  } catch {
    return false;
  }
}
function rmdirIfEmpty(dir: string): void {
  try {
    if (fs.existsSync(dir) && fs.readdirSync(dir).length === 0) {
      fs.rmdirSync(dir);
    }
  } catch {}
}
function toPosix(p: string): string {
  return p.split(path.sep).join("/");
}

