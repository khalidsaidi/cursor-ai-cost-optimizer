export function readWorkspaceAgents(workspace: string): Record<string, string | null> {
  const out: Record<string, string | null> = {};
  for (const name of CCO_AGENT_NAMES) {
    const text = readTextOr(path.join(workspace, ".cursor", "agents", `${name}.md`));
    const m = text ? text.match(/^model:\s*(.+)$/m) : null;
    out[name] = m ? m[1].trim() : null;
  }
  return out;
}

/** Extension-added files, relative to the workspace (rule, skills, commands from the bundled plugin). */
/** Only what routing needs in the workspace: the rule. Skills and chat commands stay in the extension. */
export function extensionAssetList(pluginRoot: string): string[] {
  const out: string[] = [];
  for (const rel of listFiles(path.join(pluginRoot, "rules"))) {
    out.push(`.cursor/rules/${rel}`);
  }
  return out.sort();
}

/** What an install will create/modify under <ws>/.cursor (shown before the first write). */
export function plannedFiles(workspace: string, opts: Options): { creates: string[]; modifies: string[]; hookMode: HookMode } {
  const p = workspacePaths(workspace);
  const hookMode = decideHookMode(opts);
  const creates = [".cursor/cco-hook.mjs", ".cursor/agents/cco-{fast,balanced,deep,verifier,explore}.md", ...extensionAssetList(opts.pluginRoot), ".cursor/cco/ (runtime, prices, logs; ignores itself in git)"];
  if (hookMode === "binary") {
    creates.push(`.cursor/cco/bin/${binaryFileName()}`);
  }
  creates.push(`.cursor/cco/${MANIFEST_NAME}`);
  const modifies = [fs.existsSync(p.hooksPath) ? ".cursor/hooks.json (CCO entries merged; other entries kept)" : ".cursor/hooks.json"];
  return { creates, modifies, hookMode };
}

export function decideHookMode(opts: Options): HookMode {
  const pref = opts.hookRuntime || "auto";
  const hasBinary = Boolean(opts.binaryPath && fs.existsSync(opts.binaryPath));
  if (pref === "binary") {
    if (!hasBinary) {
      throw new Error(`cco.hookRuntime is "binary" but this extension build has no hook binary for ${hostTarget()}.`);
    }
    return "binary";
  }
  if (pref === "node") {
    return "node";
  }
  // auto: Node keeps .cursor/hooks.json portable (the shim is committed next to it); the binary is the
  // fallback for machines without Node >= 18 and makes hooks.json reference a machine-local path.
  return findNode(opts.nodePath) ? "node" : hasBinary ? "binary" : "node";
}

export function workspaceStatus(workspace: string): WorkspaceStatus {
  const p = workspacePaths(workspace);
  const manifest = readJsonOr<Manifest | null>(p.manifestPath, null);
  const agents = readWorkspaceAgents(workspace);
  const cfg = readJsonOr<{ enabled?: boolean } | null>(p.configPath, null);
  const hasAgents = fs.existsSync(path.join(p.agentsDir, "cco-fast.md"));
  const hooksInstalled = Object.keys(ccoHookEntries(readJsonOr<HooksFile | null>(p.hooksPath, null))).length > 0;
  let reason: string | null = null;
  if (cfg && cfg.enabled === false) {
    reason = "workspace_opt_out";
  } else if (!hasAgents) {
    reason = "workspace_not_set_up";
  } else if (!hooksInstalled) {
    reason = "hooks_missing";
  }
  return { installed: Boolean(manifest) || (hasAgents && hooksInstalled), enabled: reason === null, reason, hookMode: manifest?.hookMode ?? (hooksInstalled ? "node" : null), agents };
}

