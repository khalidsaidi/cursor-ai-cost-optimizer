/**
 * Repair an installed workspace without touching user files: repoint plugin-path.txt and hook entries when
 * the extension path/binary path went stale (extension update, moved workspace), refresh the binary bytes,
 * and refresh the rule/skills/commands when the extension version changed. No-op where CCO was not installed.
 */
export function doctorWorkspace(workspace: string, opts: Options): DoctorResult {
  const p = workspacePaths(workspace);
  const manifest = readJsonOr<Manifest | null>(p.manifestPath, null);
  if (!manifest) {
    return { installed: false, changed: false, hookMode: null, actions: [] };
  }
  const actions: string[] = [];
  if ((readTextOr(p.pluginPathFile) || "").trim() !== opts.pluginRoot) {
    fs.writeFileSync(p.pluginPathFile, `${opts.pluginRoot}\n`, "utf8");
    actions.push("plugin_path_repointed");
  }
  let useBinary = fs.existsSync(p.binaryPath);
  const pref = opts.hookRuntime || "auto";
  if (pref !== "node" && opts.binaryPath && fs.existsSync(opts.binaryPath)) {
    if (!useBinary) {
      copyBinary(opts.binaryPath, p.binaryPath);
      actions.push("binary_installed");
      useBinary = true;
    } else if (!sameFile(opts.binaryPath, p.binaryPath)) {
      try {
        copyBinary(opts.binaryPath, p.binaryPath);
        actions.push("binary_refreshed");
      } catch (error) {
        actions.push(`binary_refresh_failed:${String((error as Error)?.message ?? error)}`);
      }
    }
  }
  if (pref === "node" && useBinary) {
    fs.rmSync(p.binDir, { recursive: true, force: true });
    actions.push("binary_removed");
    useBinary = false;
  }
  const hookMode: HookMode = useBinary ? "binary" : "node";
  const pluginHooks = readJsonOr<HooksFile>(path.join(opts.pluginRoot, "hooks", "hooks.json"), { version: 1, hooks: {} });
  const ours = buildHookEntries(pluginHooks, hookMode, useBinary ? p.binaryPath : null);
  const existing = readJsonOr<HooksFile | null>(p.hooksPath, null);
  if (!existing) {
    writeJson(p.hooksPath, mergeHooks(null, ours));
    actions.push("hooks_recreated");
  } else if (!sameEntries(ccoHookEntries(existing), ours)) {
    writeJson(p.hooksPath, mergeHooks(existing, ours));
    actions.push("hooks_repointed");
  }
  if (opts.extensionVersion && manifest.extensionVersion !== opts.extensionVersion) {
    writeExtensionAssets(workspace, opts.pluginRoot);
    actions.push("assets_refreshed");
  }
  if (actions.length) {
    manifest.hookMode = hookMode;
    manifest.binary = useBinary ? p.binaryPath : null;
    manifest.pluginRoot = opts.pluginRoot;
    manifest.extensionVersion = opts.extensionVersion ?? manifest.extensionVersion;
    manifest.files = Array.from(new Set([...manifest.files.filter((f) => !f.startsWith(".cursor/cco/bin/")), ...(useBinary ? [toPosix(path.relative(workspace, p.binaryPath))] : [])])).sort();
    writeJson(p.manifestPath, manifest);
  }
  return { installed: true, changed: actions.length > 0, hookMode, actions };
}

