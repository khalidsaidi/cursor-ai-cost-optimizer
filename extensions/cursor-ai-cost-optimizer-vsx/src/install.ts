/**
 * Install / uninstall / doctor logic for the AI Cost Optimizer extension.
 * Deliberately free of `vscode` imports so it can be unit-tested with node:test.
 *
 * Everything is PROJECT-LOCAL under <workspace>/.cursor/ (Cursor's own convention); nothing is written to
 * the home directory. The plugin's own `cco-init.mjs --workspace <ws> --no-probe` produces the layout the
 * marketplace plugin would (run with CCO_PLUGIN_ROOT = the extension's bundled plugin copy):
 *   .cursor/hooks.json          merge-preserving entries `node .cursor/cco-hook.mjs <event>` (the shim is committed next to it)
 *   .cursor/agents/cco-*.md     four tier subagents with real models (generated marker; user files never overwritten)
 *   .cursor/cco.json            settings, optional ("enabled": false opts the project out); created only when a setting is changed
 *   .cursor/cco-hook.mjs        shim (a no-op for teammates without the plugin)
 *   .cursor/cco/                plugin-path.txt (-> bundled plugin), runtime.json, pricing.json, state/ (git-ignored)
 * The extension then adds, for IDE users without the marketplace plugin and for machines without Node:
 *   .cursor/rules/cco-routing.mdc, .cursor/skills/cco-* /SKILL.md, .cursor/commands/cco*.md   (from the plugin)
 *   .cursor/cco/bin/cco-hook[.exe]   self-contained hook binary; hook commands become `"<abs binary>" <event>`
 *   .cursor/cco/extension-manifest.json   what the extension added (for uninstall/doctor)
 */
