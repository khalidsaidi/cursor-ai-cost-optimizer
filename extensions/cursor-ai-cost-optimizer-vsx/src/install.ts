/** Files earlier (pre-release) extension versions put under .cursor/cco that the plugin layout does not use. */
export function cleanupLegacyWorkspace(workspace: string): string[] {
  const p = workspacePaths(workspace);
  const removed: string[] = [];
  for (const stale of ["scripts", "config", "agents", "install-manifest.json"]) {
    const target = path.join(p.ccoDir, stale);
    if (fs.existsSync(target)) {
      fs.rmSync(target, { recursive: true, force: true });
      removed.push(toPosix(path.relative(workspace, target)));
    }
  }
  for (const stale of ["cco-runtime.json", "cco-pricing.json"]) {
    const target = path.join(p.cursorDir, stale);
    if (fs.existsSync(target)) {
      fs.rmSync(target, { force: true });
      removed.push(toPosix(path.relative(workspace, target)));
    }
  }
  return removed;
}

function writeExtensionAssets(workspace: string, pluginRoot: string): string[] {
  const written: string[] = [];
  const copy = (srcDir: string, dstDir: string, prefix: string) => {
    for (const rel of listFiles(srcDir)) {
      const to = path.join(dstDir, ...rel.split("/"));
      ensureDir(path.dirname(to));
      fs.copyFileSync(path.join(srcDir, ...rel.split("/")), to);
      written.push(`${prefix}/${rel}`);
    }
  };
  const p = workspacePaths(workspace);
  copy(path.join(pluginRoot, "rules"), p.rulesDir, ".cursor/rules");
  return written.sort();
}

/**
 * Set up a workspace: the plugin's cco-init (identical files to the marketplace plugin), then the extension's
 * additions (rule/skills/commands; binary + binary-form hook commands when in binary mode) and a manifest.
 */
export async function installWorkspace(workspace: string, opts: Options, signal?: AbortSignal): Promise<InstallResult> {
  const p = workspacePaths(workspace);
  const hookMode = decideHookMode(opts);
  const legacyRemoved = cleanupLegacyWorkspace(workspace);

  const init = await runPluginScriptAsync(workspace, "cco-init.mjs", ["--workspace", workspace, opts.probe ? "--probe" : "--no-probe"], opts, {}, signal);
  if (!init.ran) {
    throw new Error(init.error || "setup could not run");
  }
  if (init.status !== 0) {
    throw new Error(`cco-init failed (${init.runtime}): ${init.error}\n${init.stdout}`);
  }
  // cco-init pins the plugin the shim should use; make sure it is our bundled copy.
  fs.writeFileSync(p.pluginPathFile, `${opts.pluginRoot}\n`, "utf8");

  let binaryPath: string | null = null;
  fs.rmSync(p.binDir, { recursive: true, force: true });
  if (hookMode === "binary") {
    copyBinary(opts.binaryPath as string, p.binaryPath);
    binaryPath = p.binaryPath;
  }
  const hookEvents = writeHookEntries(workspace, opts, hookMode, binaryPath);

  const previous = readJsonOr<Manifest | null>(p.manifestPath, null);
  const files = writeExtensionAssets(workspace, opts.pluginRoot);
  for (const stale of (previous?.files || []).filter((f) => !files.includes(f) && !f.startsWith(".cursor/cco/"))) {
    fs.rmSync(path.join(workspace, ...stale.split("/")), { force: true });
  }
  if (binaryPath) {
    files.push(toPosix(path.relative(workspace, binaryPath)));
  }
  const manifest: Manifest = { version: 4, extensionVersion: opts.extensionVersion, installedAt: new Date().toISOString(), hookMode, pluginRoot: opts.pluginRoot, binary: binaryPath, files: files.sort() };
  writeJson(p.manifestPath, manifest);
  return { workspace, hookMode, binaryPath, hooksPath: p.hooksPath, hookEvents, files: manifest.files, agents: readWorkspaceAgents(workspace), init, manifestPath: p.manifestPath, legacyRemoved };
}

